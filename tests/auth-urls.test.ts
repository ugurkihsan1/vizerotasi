import { expect, it } from "vitest";
import { createClient } from "@supabase/supabase-js";
import {
  isTrustedAuthReturnUrl,
  isTrustedOAuthUrl,
} from "../src/lib/auth-urls";

const project = "https://test-project.supabase.co";
const callback = "vizerotasi://auth?oauth=1";
function authorize(redirect = callback) {
  return `${project}/auth/v1/authorize?provider=google&redirect_to=${encodeURIComponent(redirect)}`;
}
it("accepts URLs generated by the installed Supabase SDK for both providers", async () => {
  const client = createClient(
    project,
    "sb_publishable_public_fixture_not_a_real_key",
    {
      auth: {
        persistSession: false,
        autoRefreshToken: false,
        detectSessionInUrl: false,
      },
    },
  );
  for (const provider of ["google", "apple"] as const) {
    const { data, error } = await client.auth.signInWithOAuth({
      provider,
      options: {
        redirectTo: callback,
        skipBrowserRedirect: true,
        ...(provider === "google"
          ? { queryParams: { prompt: "select_account" } }
          : {}),
      },
    });
    expect(error).toBeNull();
    expect(isTrustedOAuthUrl(data.url!, project, provider, callback)).toBe(
      true,
    );
  }
});
it.each([
  "https://evil.example/auth/v1/authorize",
  authorize().replace(project, `${project}.evil.example`),
  authorize().replace(project, "https://other.supabase.co"),
  authorize().replace(project, "https://test-project.supabase.co@evil.example"),
  authorize().replace(project, "https://evil.example@test-project.supabase.co"),
  authorize().replace("https:", "http:"),
  authorize().replace(project, `${project}:8443`),
  authorize().replace("/auth/v1/authorize", "/auth/v1/callback"),
  authorize().replace("/auth/v1/authorize", "/auth/v1/%61uthorize"),
  authorize().replace("/auth/v1/authorize", "//evil.example"),
  authorize("https://evil.example/auth"),
  authorize() + "&redirect_to=https%3A%2F%2Fevil.example",
  authorize() + "&provider=apple",
  authorize() + "&next=https%3A%2F%2Fevil.example",
  authorize() + "#https://evil.example",
  authorize() + "&skip_http_redirect=false",
  "javascript:alert(1)",
  "//evil.example/auth/v1/authorize",
  " " + authorize(),
  authorize().replace("test-project.", "test-project.\n"),
  authorize().replace("https://", "https:\\\\"),
])("blocks the untrusted authorization URL %s", (url) => {
  expect(isTrustedOAuthUrl(url, project, "google", callback)).toBe(false);
});
it("accepts tokens and errors only at the requested callback destination", () => {
  expect(
    isTrustedAuthReturnUrl(
      callback + "#access_token=a&refresh_token=b",
      callback,
    ),
  ).toBe(true);
  expect(
    isTrustedAuthReturnUrl(callback + "#error=access_denied", callback),
  ).toBe(true);
  const web = "https://ugurkihsan1.github.io/vizerotasi/auth?oauth=1";
  expect(
    isTrustedAuthReturnUrl(web + "#access_token=a&refresh_token=b", web),
  ).toBe(true);
  for (const url of [
    "https://evil.example/auth?oauth=1",
    "vizerotasi://evil?oauth=1",
    "vizerotasi://auth/other?oauth=1",
    "vizerotasi://auth:1234?oauth=1",
    "vizerotasi://auth?oauth=0",
    callback + "&oauth=0",
    "vizerotasi://evil@auth?oauth=1",
    "javascript:alert(1)",
  ])
    expect(isTrustedAuthReturnUrl(url, callback)).toBe(false);
  expect(
    isTrustedAuthReturnUrl(
      web.replace("ugurkihsan1.github.io", "evil.example"),
      web,
    ),
  ).toBe(false);
});
